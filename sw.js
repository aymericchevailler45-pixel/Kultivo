// Installation : on garde une première copie de tout le jeu
self.addEventListener('install', event => {
    event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)));
    self.skipWaiting();
});

// Activation : on supprime les anciennes copies et on prend la main tout de suite
self.addEventListener('activate', event => {
    event.waitUntil(
        caches.keys()
            .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
            .then(() => self.clients.claim())
    );
});

// Chaque fichier : d'abord internet (et on met la copie à jour), sinon la copie
self.addEventListener('fetch', event => {
    const request = event.request;
    if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

    // Fichiers du jeu (page, code, styles) : on contourne la copie de 10 minutes des serveurs de GitHub
    // en ajoutant un paramètre unique → toujours la toute dernière version. Images : requête normale.
    const url = new URL(request.url);
    const isCode = request.mode === 'navigate' || url.pathname.endsWith('/') || /\.(html|js|css|json)$/.test(url.pathname);
    const target = isCode ? `${url.origin}${url.pathname}?v=${Date.now()}` : request;

    event.respondWith(
        fetch(target, { cache: 'no-store' })
            .then(response => {
                if (response.ok) {
                    const copy = response.clone();
                    caches.open(CACHE).then(cache => cache.put(request, copy));
                }
                return response;
            })
            .catch(() => caches.match(request).then(found => found || caches.match('./index.html')))
    );
});
